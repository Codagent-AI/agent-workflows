#!/usr/bin/env bash
set -euo pipefail

# create-release-pr.sh — Update VERSION, prepend the changelog section, sync every
# version file, rebuild the define plugin's bundle, then commit and push.
# If on a non-main branch with an open PR, pushes to that branch.
# If on main, creates a release branch and PR.
# Usage: create-release-pr.sh <new-version> <changelog-section-file>

REPO="${GITHUB_REPOSITORY:-Codagent-AI/agent-workflows}"
VERSION_FILE="VERSION"
CHANGELOG="CHANGELOG.md"
SERVER_DIR="human-workflows/openspec/server"

NEW_VERSION="${1:?Usage: create-release-pr.sh <new-version> <changelog-section-file>}"
CHANGELOG_FILE="${2:?Usage: create-release-pr.sh <new-version> <changelog-section-file>}"

if [[ ! "$NEW_VERSION" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
  echo "Error: invalid version: $NEW_VERSION" >&2
  exit 1
fi

if [ ! -f "$CHANGELOG_FILE" ]; then
  echo "Error: changelog section file not found: $CHANGELOG_FILE" >&2
  exit 1
fi

if [ -n "$(git status --porcelain)" ]; then
  echo "Error: the working tree is not clean. Commit or stash your changes first." >&2
  exit 1
fi

CURRENT_BRANCH=$(git branch --show-current)

if [ "$CURRENT_BRANCH" = "main" ]; then
  # A release PR already open for this version is updated from its own branch, where the
  # branch PR must be open: check it out, bring main into it, and run the skill there.
  RELEASE_BRANCH="release/v${NEW_VERSION}"
  git fetch -q origin "$RELEASE_BRANCH" 2>/dev/null || true
  if git rev-parse --verify -q "refs/remotes/origin/${RELEASE_BRANCH}" >/dev/null; then
    echo "Error: ${RELEASE_BRANCH} already exists on origin. Check it out, merge origin/main into it, and run the release skill from that branch." >&2
    exit 1
  fi
  git checkout -q -b "$RELEASE_BRANCH"
  # A failure before the commit leaves edits on a new branch, so say how to start over.
  trap 'echo "Failed before the release commit. To start over: git restore . && git switch main && git branch -D ${RELEASE_BRANCH}, then rerun the skill." >&2' ERR
else
  BRANCH_PR=$(gh pr view --json number,state,url,baseRefName 2>&1) || {
    echo "Error: current branch has no associated PR. Create a PR before adding release changes to a feature branch." >&2
    exit 1
  }
  BRANCH_PR_STATE=$(echo "$BRANCH_PR" | jq -r '.state')
  BRANCH_PR_BASE=$(echo "$BRANCH_PR" | jq -r '.baseRefName // ""')
  if [ "$BRANCH_PR_STATE" != "OPEN" ] || [ "$BRANCH_PR_BASE" != "main" ]; then
    echo "Error: the branch PR must be open and target main (it is ${BRANCH_PR_STATE}, base ${BRANCH_PR_BASE})." >&2
    echo "$BRANCH_PR" | jq -r '.url' >&2
    exit 1
  fi
fi

printf '%s\n' "$NEW_VERSION" > "$VERSION_FILE"
node scripts/sync-versions.mjs

# Build from main's changelog, so a section written by an earlier run of this
# skill for an unreleased version is replaced, whatever its version.
BASE_CHANGELOG=$(mktemp)
git show "origin/main:${CHANGELOG}" > "$BASE_CHANGELOG" 2>/dev/null || cp "$CHANGELOG" "$BASE_CHANGELOG" 2>/dev/null || true
if [ -s "$BASE_CHANGELOG" ]; then
  {
    head -1 "$BASE_CHANGELOG"
    echo ""
    cat "$CHANGELOG_FILE"
    echo ""
    tail -n +3 "$BASE_CHANGELOG"
  } > "$CHANGELOG"
else
  {
    echo "# agent-workflows"
    echo ""
    cat "$CHANGELOG_FILE"
  } > "$CHANGELOG"
fi
rm -f "$BASE_CHANGELOG"

# The bundle carries the version, so it is rebuilt, and the build and its check must pass.
(cd "$SERVER_DIR" && npm ci --no-audit --no-fund --silent && node scripts/build.mjs && node scripts/build.mjs --check)
node scripts/sync-versions.mjs --check

git add "$VERSION_FILE" "$CHANGELOG" .claude-plugin/marketplace.json \
  human-workflows/openspec/plugin/.claude-plugin/plugin.json \
  human-workflows/openspec/plugin/.codex-plugin/plugin.json \
  human-workflows/openspec/plugin/server.mjs \
  human-workflows/archon/plugin/.claude-plugin/plugin.json \
  human-workflows/archon/plugin/.codex-plugin/plugin.json \
  "$SERVER_DIR/package.json" "$SERVER_DIR/package-lock.json"
git diff --cached --quiet || git commit -q -m "chore: release v${NEW_VERSION}"
if [ "$CURRENT_BRANCH" = "main" ]; then
  # The commit exists now, so a failure is finished by pushing and opening the PR.
  trap 'echo "Failed. To finish by hand: git push -u origin ${RELEASE_BRANCH} && gh pr create --repo ${REPO} --base main --head ${RELEASE_BRANCH} --title \"chore: release v${NEW_VERSION}\" --fill" >&2' ERR
fi

if [ "$CURRENT_BRANCH" = "main" ]; then
  git push -q -u origin "release/v${NEW_VERSION}"
  gh pr create --repo "$REPO" --base main \
    --title "chore: release v${NEW_VERSION}" \
    --body "$(cat <<BODY
## Release v${NEW_VERSION}

This PR was generated by the \`/release\` skill.

When merged, the release workflow tags \`v${NEW_VERSION}\`, creates the GitHub release from the changelog, and attaches the pack tarball.
BODY
)"
else
  if git rev-parse --abbrev-ref --symbolic-full-name '@{u}' >/dev/null 2>&1; then
    git push -q
  else
    git push -q -u origin "$CURRENT_BRANCH"
  fi
  gh pr view "$CURRENT_BRANCH" --repo "$REPO" --json url --jq .url
fi
